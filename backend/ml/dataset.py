"""Deterministic synthetic training dataset for the prototype flood classifier.

HONESTY NOTE
------------
This dataset is generated by a fixed, seeded formula. It is NOT observed
historical flood data, it is not derived from any real gauge network, and no
metric computed on it says anything about real-world forecast skill. It exists
so the prototype can demonstrate a genuinely trained model end to end.

The eight features match app/integrations/ml_signal.FEATURE_ORDER exactly, in
the same order and the same units, so training and inference cannot drift.
"""
from __future__ import annotations

import random
from typing import Dict, List, Sequence, Tuple

FEATURE_ORDER: Tuple[str, ...] = (
    "rainfall_mm_h",
    "humidity_pct",
    "temperature_c",
    "drainage_score",
    "previous_flood",
    "elevation_m",
    "population_density",
    "soil_saturation",
)

FEATURE_UNITS = {
    "rainfall_mm_h": "mm/h",
    "humidity_pct": "percent",
    "temperature_c": "degrees Celsius",
    "drainage_score": "0-100, higher is better drainage",
    "previous_flood": "0 or 1",
    "elevation_m": "metres above district datum",
    "population_density": "people per square km",
    "soil_saturation": "percent",
}

DEFAULT_SEED = 20260910
DEFAULT_SAMPLES = 3000
LABEL_NAMES = ("flood_unlikely", "flood_likely")
DATA_LABEL = "SYNTHETIC TRAINING DATA - GENERATED, NOT OBSERVED"

# Latent generator weights describing the synthetic world only. These are not
# the operational risk weights, which live in app/intelligence/risk.py and are
# never learned from data.
LATENT_WEIGHTS = {
    "rainfall": 0.34,
    "soil": 0.20,
    "drainage_deficit": 0.18,
    "low_elevation": 0.16,
    "previous_flood": 0.08,
    "humidity": 0.04,
}
DECISION_THRESHOLD = 0.50
NOISE_SCALE = 0.06


def _scale(value: float, low: float, high: float) -> float:
    if high <= low:
        return 0.0
    if value <= low:
        return 0.0
    if value >= high:
        return 1.0
    return (value - low) / (high - low)


def latent_probability(row: Sequence[float]) -> float:
    """The generating function: a smooth, monotone latent flood propensity."""
    rainfall = float(row[0])
    humidity = float(row[1])
    drainage = float(row[3])
    previous = float(row[4])
    elevation = float(row[5])
    soil = float(row[7])
    parts = {
        "rainfall": _scale(rainfall, 0.0, 60.0) ** 0.85,
        "soil": _scale(soil, 20.0, 100.0),
        "drainage_deficit": 1.0 - _scale(drainage, 15.0, 95.0),
        "low_elevation": 1.0 - _scale(elevation, 2.0, 55.0),
        "previous_flood": 1.0 if previous >= 0.5 else 0.0,
        "humidity": _scale(humidity, 55.0, 100.0),
    }
    score = sum(LATENT_WEIGHTS[name] * value for name, value in parts.items())
    # Interaction: heavy rain on saturated ground is worse than the sum.
    score += 0.10 * parts["rainfall"] * parts["soil"]
    return min(1.0, max(0.0, score))


def _sample_row(rng: random.Random) -> List[float]:
    wet_regime = rng.random() < 0.45
    if wet_regime:
        rainfall = rng.uniform(8.0, 85.0)
        humidity = rng.uniform(72.0, 99.0)
        soil = rng.uniform(45.0, 100.0)
    else:
        rainfall = rng.uniform(0.0, 18.0)
        humidity = rng.uniform(52.0, 88.0)
        soil = rng.uniform(12.0, 65.0)
    return [
        round(rainfall, 3),
        round(humidity, 3),
        round(rng.uniform(21.0, 36.0), 3),
        round(rng.uniform(15.0, 95.0), 3),
        float(1 if rng.random() < 0.30 else 0),
        round(rng.uniform(2.0, 58.0), 3),
        round(rng.uniform(400.0, 21000.0), 1),
        round(soil, 3),
    ]


def build_dataset(samples: int = DEFAULT_SAMPLES,
                  seed: int = DEFAULT_SEED) -> Dict[str, object]:
    """Generate the dataset. The same seed always produces the same rows."""
    rng = random.Random(seed)
    features: List[List[float]] = []
    labels: List[int] = []
    for _ in range(int(samples)):
        row = _sample_row(rng)
        probability = latent_probability(row)
        noisy = probability + rng.gauss(0.0, NOISE_SCALE)
        features.append(row)
        labels.append(1 if noisy >= DECISION_THRESHOLD else 0)
    positives = sum(labels)
    return {
        "features": features,
        "labels": labels,
        "feature_names": list(FEATURE_ORDER),
        "feature_units": dict(FEATURE_UNITS),
        "label_names": list(LABEL_NAMES),
        "seed": int(seed),
        "samples": len(labels),
        "positive_rate": round(positives / max(1, len(labels)), 6),
        "data_label": DATA_LABEL,
    }


def train_test_split(features: Sequence[Sequence[float]], labels: Sequence[int],
                     test_fraction: float = 0.25,
                     seed: int = DEFAULT_SEED) -> Dict[str, List]:
    """Deterministic shuffled split, no third-party dependency required."""
    order = list(range(len(labels)))
    random.Random(seed + 1).shuffle(order)
    cut = int(len(order) * (1.0 - float(test_fraction)))
    train_idx = order[:cut]
    test_idx = order[cut:]
    return {
        "x_train": [list(features[i]) for i in train_idx],
        "y_train": [int(labels[i]) for i in train_idx],
        "x_test": [list(features[i]) for i in test_idx],
        "y_test": [int(labels[i]) for i in test_idx],
    }


if __name__ == "__main__":  # pragma: no cover - manual inspection
    data = build_dataset()
    print(DATA_LABEL)
    print("samples", data["samples"], "positive rate", data["positive_rate"])
    print("features", data["feature_names"])
    print("first row", data["features"][0], "->", data["labels"][0])
