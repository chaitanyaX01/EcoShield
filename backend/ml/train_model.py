"""Train the prototype flood classifier and write a real artefact.

Run from the backend directory:

    python ml/train_model.py

Behaviour:
  * uses scikit-learn's ExtraTreesClassifier when it can be imported
  * otherwise falls back to the vendored Extra Trees implementation in
    ml/extra_trees.py so training still really happens offline
  * evaluates on a held-out split and writes the REAL metrics into
    ml/artifacts/model_metadata.json - no metric in this project is invented
  * persists the fitted model with joblib when available, else pickle

The artefact is consumed by app/integrations/ml_signal.MLSignalAdapter, which
treats the output as evidence only. It never enters the deterministic risk
formula.
"""
from __future__ import annotations

import json
import os
import sys
import time
from typing import Any, Dict, List

HERE = os.path.dirname(os.path.abspath(__file__))
BACKEND = os.path.dirname(HERE)
if BACKEND not in sys.path:
    sys.path.insert(0, BACKEND)

from ml import dataset as dataset_mod  # noqa: E402
from ml import metrics as metrics_mod  # noqa: E402

MODEL_VERSION = "flood-extratrees-proto-1.0.0"
ARTIFACT_DIR = os.path.join(HERE, "artifacts")
HYPERPARAMETERS = {
    "n_estimators": 120,
    "max_depth": 12,
    "min_samples_split": 8,
    "max_features": 3,
    "random_state": dataset_mod.DEFAULT_SEED,
}
UI_LABEL = "Prototype ML signal - trained on synthetic demonstration data"
LIMITATIONS = [
    "Trained on a deterministic synthetic dataset generated by ml/dataset.py.",
    "Metrics describe that synthetic data only and imply nothing about real "
    "world forecast skill.",
    "The signal is evidence for the operator. It does not change the "
    "deterministic risk score and cannot override safety logic.",
]


def _build_model() -> Any:
    """scikit-learn if importable, vendored implementation otherwise."""
    try:
        from sklearn.ensemble import ExtraTreesClassifier  # type: ignore

        model = ExtraTreesClassifier(
            n_estimators=HYPERPARAMETERS["n_estimators"],
            max_depth=HYPERPARAMETERS["max_depth"],
            min_samples_split=HYPERPARAMETERS["min_samples_split"],
            max_features=HYPERPARAMETERS["max_features"],
            random_state=HYPERPARAMETERS["random_state"],
            n_jobs=-1,
        )
        return model, "scikit-learn ExtraTreesClassifier"
    except ImportError:
        from ml.extra_trees import ExtraTreesClassifier as VendoredExtraTrees

        model = VendoredExtraTrees(**HYPERPARAMETERS)
        return model, "vendored ExtraTreesClassifier (scikit-learn unavailable)"


def _persist(model: Any) -> str:
    os.makedirs(ARTIFACT_DIR, exist_ok=True)
    try:
        import joblib  # type: ignore

        name = "flood_extra_trees.joblib"
        joblib.dump(model, os.path.join(ARTIFACT_DIR, name))
        return name
    except ImportError:
        import pickle

        name = "flood_extra_trees.pkl"
        with open(os.path.join(ARTIFACT_DIR, name), "wb") as handle:
            pickle.dump(model, handle)
        return name


def _positive_scores(model: Any, rows: List[List[float]]) -> List[float]:
    proba = model.predict_proba(rows)
    return [float(row[1]) if len(row) > 1 else float(row[0]) for row in proba]


def _importances(model: Any, names: List[str]) -> Dict[str, float]:
    raw = getattr(model, "feature_importances_", None)
    if raw is None:
        return {}
    return {name: round(float(value), 6) for name, value in zip(names, list(raw))}


def train(samples: int = dataset_mod.DEFAULT_SAMPLES,
          seed: int = dataset_mod.DEFAULT_SEED) -> Dict[str, Any]:
    data = dataset_mod.build_dataset(samples=samples, seed=seed)
    split = dataset_mod.train_test_split(
        data["features"], data["labels"], test_fraction=0.25, seed=seed
    )
    model, implementation = _build_model()

    started = time.time()
    model.fit(split["x_train"], split["y_train"])
    fit_seconds = round(time.time() - started, 3)

    test_metrics = metrics_mod.evaluate(
        split["y_test"], _positive_scores(model, split["x_test"])
    )
    train_metrics = metrics_mod.evaluate(
        split["y_train"], _positive_scores(model, split["x_train"])
    )
    artifact_file = _persist(model)

    metadata: Dict[str, Any] = {
        "artifact_file": artifact_file,
        "model_version": MODEL_VERSION,
        "implementation": implementation,
        "algorithm": "Extra Trees (extremely randomized trees) classifier",
        "trained_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "hyperparameters": HYPERPARAMETERS,
        "feature_order": list(dataset_mod.FEATURE_ORDER),
        "feature_units": dataset_mod.FEATURE_UNITS,
        "label_names": list(dataset_mod.LABEL_NAMES),
        "dataset": {
            "generator": "ml/dataset.py",
            "data_label": dataset_mod.DATA_LABEL,
            "samples": data["samples"],
            "seed": data["seed"],
            "positive_rate": data["positive_rate"],
            "train_samples": len(split["y_train"]),
            "test_samples": len(split["y_test"]),
            "test_fraction": 0.25,
        },
        "metrics": test_metrics,
        "train_metrics": train_metrics,
        "feature_importances": _importances(model, list(dataset_mod.FEATURE_ORDER)),
        "fit_seconds": fit_seconds,
        "ui_label": UI_LABEL,
        "limitations": LIMITATIONS,
        "role": "evidence_only",
        "affects_risk_score": False,
    }

    os.makedirs(ARTIFACT_DIR, exist_ok=True)
    with open(os.path.join(ARTIFACT_DIR, "model_metadata.json"), "w",
              encoding="utf-8") as handle:
        json.dump(metadata, handle, indent=2, sort_keys=True)
        handle.write("\n")
    return metadata


def main() -> None:
    metadata = train()
    metrics = metadata["metrics"]
    print("Trained: " + str(metadata["implementation"]))
    print("Artefact: " + os.path.join("ml/artifacts", str(metadata["artifact_file"])))
    print("Dataset: " + str(metadata["dataset"]["samples"]) + " synthetic samples, "
          + "positive rate " + str(metadata["dataset"]["positive_rate"]))
    print("Held-out metrics (real, measured on this run):")
    for name in ("samples", "accuracy", "precision", "recall", "f1", "roc_auc",
                 "brier_score"):
        print("  " + name + ": " + str(metrics[name]))
    print("  confusion: " + json.dumps(metrics["confusion_matrix"]))
    print("Feature importances:")
    for name, value in sorted(metadata["feature_importances"].items(),
                              key=lambda item: -item[1]):
        print("  " + name + ": " + str(value))
    print(UI_LABEL)


if __name__ == "__main__":
    main()
